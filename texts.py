def flames_word(count: int) -> str:
    n = abs(count) % 100
    if 11 <= n <= 14:
        return "огоньков"
    last = n % 10
    if last == 1:
        return "огонёк"
    if 2 <= last <= 4:
        return "огонька"
    return "огоньков"

def format_voice(seconds: int) -> str:
    seconds = max(0, int(seconds))
    return f"{seconds // 60}:{seconds % 60:02d}"

def format_goal_time(seconds: int) -> str:
    minutes = seconds // 60
    secs = seconds % 60
    if secs == 0:
        return f"{minutes} мин."
    return f"{minutes} мин. {secs} сек."
